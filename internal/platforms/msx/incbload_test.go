// writeIncbloadFixture creates a companion rotina.asm/.bin/.sym trio
// in dir, mirroring what a real `compile rotina.asm` (ver asmsx.go)
// would have already produced before the .dmx using [INCBLOAD] is
// compiled.
func writeIncbloadFixture(t *testing.T, dir string) {
	t.Helper()
	asmPath := filepath.Join(dir, "rotina.asm")
	if err := os.WriteFile(asmPath, []byte(".ORG $8000\nInit:\nRET\n.START Init\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "rotina.bin"), []byte{0xC9}, 0o644); err != nil {
		t.Fatal(err)
	}
	writeSymFixture(t, dir, "rotina.sym")
}

func TestCompileFileExpandsIncbloadToBloadAndDefusr(t *testing.T) {
	dir := t.TempDir()
	writeIncbloadFixture(t, dir)

	dmxPath := filepath.Join(dir, "game.dmx")
	src := "x=1\n[INCBLOAD](\"rotina.asm\")\nprint USR(0)\n"
	if err := os.WriteFile(dmxPath, []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}

	amxPath, _, err := CompileFile(dmxPath, nil)
	if err != nil {
		t.Fatalf("CompileFile: %v", err)
	}
	listing, err := os.ReadFile(amxPath)
	if err != nil {
		t.Fatal(err)
	}
	got := strings.ToUpper(string(listing))
	if !strings.Contains(got, `BLOAD "ROTINA.BIN"`) {
		t.Fatalf(`listing = %q, want it to contain BLOAD "ROTINA.BIN"`, listing)
	}
	if !strings.Contains(got, "DEFUSR=&H8010") {
		t.Fatalf("listing = %q, want it to contain DEFUSR=&H8010", listing)
	}
}

func TestCompileFileFailsWhenTheAsmHasNotBeenCompiledYet(t *testing.T) {
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "rotina.asm"), []byte(".ORG $8000\n"), 0o644); err != nil {
		t.Fatal(err)
	}

	dmxPath := filepath.Join(dir, "game.dmx")
	src := "[INCBLOAD](\"rotina.asm\")\n"
	if err := os.WriteFile(dmxPath, []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}

	_, _, err := CompileFile(dmxPath, nil)
	if err == nil {
		t.Fatal("CompileFile with no rotina.bin yet: want error, got nil")
	}
	if !strings.Contains(err.Error(), "rotina.bin") {
		t.Fatalf("error = %v, want it to name rotina.bin", err)
	}
}
