func TestParseAsmNumberAcceptsAllThreeHexConventionsAndDecimal(t *testing.T) {
	cases := []struct {
		tok  string
		want int
	}{
		{"0x8a", 0x8a},
		{"0X8A", 0x8a},
		{"$8a", 0x8a},
		{"$FF", 0xff},
		{"10h", 0x10},
		{"0FFh", 0xff},
		{"32768", 32768},
	}
	for _, c := range cases {
		got, ok := parseAsmNumber(c.tok)
		if !ok {
			t.Errorf("parseAsmNumber(%q): want ok, got not-ok", c.tok)
			continue
		}
		if got != c.want {
			t.Errorf("parseAsmNumber(%q) = %d, want %d", c.tok, got, c.want)
		}
	}
}

func TestParseAsmNumberRejectsALabelName(t *testing.T) {
	if _, ok := parseAsmNumber("Init"); ok {
		t.Fatal("parseAsmNumber(\"Init\"): want not-ok, got ok")
	}
}

func TestFindLastDirectiveArgStripsCommentsAndPicksTheLastMatch(t *testing.T) {
	src := "; header\n.ORG $8000 ; base address\nNOP\n.ORG $9000\n; .ORG $FFFF (commented out)\n"
	got, ok := findLastDirectiveArg(src, ".ORG")
	if !ok || got != "$9000" {
		t.Fatalf("findLastDirectiveArg = (%q, %v), want (%q, true)", got, ok, "$9000")
	}
}

func TestFindLastDirectiveArgReturnsFalseWhenAbsent(t *testing.T) {
	if _, ok := findLastDirectiveArg(".ORG $8000\n", ".START"); ok {
		t.Fatal("findLastDirectiveArg(\".START\"): want not-ok, got ok")
	}
}

func writeSymFixture(t *testing.T, dir, name string) string {
	t.Helper()
	path := filepath.Join(dir, name)
	content := "; Symbol table from rotina.asm\n; generated by asMSX v5.3\n\n" +
		"; global and local labels\n8010h Init\n8020h Loop\n"
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
	return path
}

func TestParseSymFileReadsLabelsCaseInsensitively(t *testing.T) {
	dir := t.TempDir()
	symbols, err := parseSymFile(writeSymFixture(t, dir, "rotina.sym"))
	if err != nil {
		t.Fatalf("parseSymFile: %v", err)
	}
	if symbols["INIT"] != 0x8010 {
		t.Fatalf("symbols[INIT] = %#x, want %#x", symbols["INIT"], 0x8010)
	}
	if symbols["LOOP"] != 0x8020 {
		t.Fatalf("symbols[LOOP] = %#x, want %#x", symbols["LOOP"], 0x8020)
	}
}

